﻿using System.Globalization;
using System.Text;

namespace Tal
{
    public static class Mol2Writer
    {
        public static bool Write(StructureData s, string path)
        {
            var sb = new StringBuilder();

            sb.AppendLine("@<TRIPOS>MOLECULE");
            sb.AppendLine(string.IsNullOrEmpty(s.Name) ? "TAL_molecule" : s.Name);
            sb.AppendLine(string.Format(CultureInfo.InvariantCulture,
                "{0,5} {1,5} {2,5} {3,5} {4,5}",
                s.Atoms.Count, 0, 1, 0, 0));
            sb.AppendLine("SMALL");
            sb.AppendLine("NO_CHARGES");
            sb.AppendLine("****");
            sb.AppendLine("Generated by TAL");

            sb.AppendLine("@<TRIPOS>ATOM");
            int id = 1;
            foreach (var a in s.Atoms)
            {
                string sybyl = a.Symbol; // simple – can be improved later
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture,
                    "{0,7} {1,-8} {2,9:F4} {3,9:F4} {4,9:F4} {5,-7} {6,5} {7,-6} {8,8:F4}",
                    id, a.Name, a.X, a.Y, a.Z, sybyl, 1, "RES1", 0.0));
                id++;
            }

 // Optional CRYSIN
            if (s.a > 0.1f)
            {
                sb.AppendLine("@<TRIPOS>CRYSIN");
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture,
                    "{0,10:F4} {1,10:F4} {2,10:F4} {3,9:F4} {4,9:F4} {5,9:F4} {6,5} {7,5}",
                    s.a, s.b, s.c, s.alpha, s.beta, s.gamma,
                    s.SpaceGroup > 0 ? s.SpaceGroup : 1, 1));
            }

            File.WriteAllText(path, sb.ToString(), Encoding.ASCII);
            return true;
        }
    }
}