﻿using System.Globalization;
using System.Text;

namespace Tal
{
    public static class XyzWriter
    {
        public static bool Write(StructureData s, string path)
        {
            var sb = new StringBuilder();
            sb.AppendLine(s.Atoms.Count.ToString());
            sb.AppendLine(string.IsNullOrEmpty(s.Name) ? "Generated by TAL" : s.Name);

            foreach (var a in s.Atoms)
            {
 // XYZ expects Cartesian – if we have cell we could convert, 
 // but for simplicity we write whatever is stored (most non-crystal formats keep Cartesian)
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture,
                    "{0,-3} {1,12:F6} {2,12:F6} {3,12:F6}",
                    a.Symbol, a.X, a.Y, a.Z));
            }

            File.WriteAllText(path, sb.ToString(), Encoding.UTF8);
            return true;
        }
    }
}