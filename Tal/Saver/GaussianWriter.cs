﻿using System.Globalization;
using System.Text;

namespace Tal
{
    public static class GaussianWriter
    {
        public static bool Write(StructureData s, string path)
        {
            var sb = new StringBuilder();

            sb.AppendLine("%chk=" + Path.GetFileNameWithoutExtension(path) + ".chk");
            sb.AppendLine("#p B3LYP/6-31G(d) Opt");
            sb.AppendLine();
            sb.AppendLine(string.IsNullOrEmpty(s.Name) ? "Generated by TAL" : s.Name);
            sb.AppendLine();
            sb.AppendLine("0 1");          // charge multiplicity – can be extended later

            foreach (var a in s.Atoms)
            {
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture,
                    "{0,-3} {1,12:F6} {2,12:F6} {3,12:F6}",
                    a.Symbol, a.X, a.Y, a.Z));
            }

            sb.AppendLine(); // important trailing blank line
            File.WriteAllText(path, sb.ToString(), Encoding.ASCII);
            return true;
        }
    }
}