 /// <summary>
 /// Main method for generating the 3D representation.
 /// </summary>
 /// <param name="p">Generation mode: 0=asymmetric, 1=symmetry, 2=packing.</param>
 /// <param name="style">Rendering style.</param>
        public void Presentation(int p, int style)
        {
            Debug.WriteLine("========================================");
            Debug.WriteLine($"[Presentation] START p={p}, style={style}");
            Debug.WriteLine($"  AsymmetricPart.Count={AsymmetricPart.Count}");
            Debug.WriteLine("========================================");

            ExpandedAtomIndices.Clear();
            HBondNeighborAtomIndices.Clear();

            CenterAsymmetricPart3D();

 // Step 1: Generate symmetry equivalents
            CalculateSymmetryEquivalents();
            Debug.WriteLine($"[Presentation] SymetryEquivalents.Count={SymetryEquivalents.Count}");

 // Step 2: Calculate charges
            CalculateAndAssignCharges(ChargeMethod.SQE);

 // Step 3: Calculate hydrophobicity
            CalculateAndAssignHydrophobicity();

 // ═══════════════════════════════════════════════════════════════
 // Step 4: Detect molecules
 //
 // ⭐ ZAWSZE na SymetryEquivalents (full cell).
 // Reason: molecule may be generated by a symmetry operation
 // from the independent part — then only SymmetryEquivalents contain
 // the COMPLETE molecule. Only then do we propagate the result to
 // AsymmetricPart (mapping after positions frakcjonalnej).
 // ═══════════════════════════════════════════════════════════════
            DetectMolecules(SymetryEquivalents, true);
            PrintMoleculeStatistics(SymetryEquivalents, "SymetryEquivalents");

 // Propaguj IndividualMoleculeInCell z SymetryEquivalents do AsymmetricPart
            PropagateMoleculeIdsToAsymmetricPart();

 // Step 5: Generate 3D atoms
            switch (p)
            {
                case 0:

                    Debug.WriteLine("[Presentation] CASE 0: ASYMMETRIC");
                    NumberOfAtoms = Calculate_SymmetryAtoms3D(0, 1, 0, 1, 0, 1, AsymmetricPart, style);
                    break;
                case 1:
                    {
                        Debug.WriteLine("[Presentation] CASE 1: SYMMETRY");
                        CenterMolecules3D();
                        NumberOfAtoms = Calculate_SymmetryAtoms3D(0, 1, 0, 1, 0, 1, SymetryEquivalents, style);
                        break;
                    }
                case 2:
                    {
                        Debug.WriteLine("[Presentation] CASE 2: PACKING");
                        float minX = Flags.Instance.ShiftNegativeX;
                        float maxX = Flags.Instance.ShiftPositiveX;
                        float minY = Flags.Instance.ShiftNegativeY;
                        float maxY = Flags.Instance.ShiftPositiveY;
                        float minZ = Flags.Instance.ShiftNegativeZ;
                        float maxZ = Flags.Instance.ShiftPositiveZ;

                        CenterMolecules3D();

                        Debug.WriteLine(
                            $"[Presentation] PACKING box: X[{minX:F2},{maxX:F2}] Y[{minY:F2},{maxY:F2}] Z[{minZ:F2},{maxZ:F2}]");
                        NumberOfAtoms = Calculate_SymmetryAtoms3D_Packing(
                            minX, maxX, minY, maxY, minZ, maxZ, SymetryEquivalents, style);
                        break;
                    }
                default:
                    Debug.WriteLine($"[Presentation] CASE DEFAULT: {p}");
                    NumberOfAtoms = Calculate_SymmetryAtoms3D(0, 1, 0, 1, 0, 1, AsymmetricPart, style);
                    break;
            }

            Debug.WriteLine($"[Presentation] NumberOfAtoms={NumberOfAtoms}");

 // Step 6: Copy properties to 3D atoms
            CopyChargesTo3DAtoms();
            CopyHydrophobicityTo3DAtoms();

 // Step 7: Center and calculate bonds
            CenterAtoms3D();
            Calculate_Bonds3D();
            Calculate_Hbonds3D();
            PrecomputeBondMatrices();
            PrepareUnitCell();
            InitializeLabelOffsets();

 // Afterlyhedrals — detection after 3D atoms are generated
            if (style == 4)
            {
                Polihedrals.CurrentMolecule = this;
                Polihedrals.FindPolihedral();
            }
            else
            {
                Polihedrals.Clear();
            }

            Debug.WriteLine("[Presentation] END");
            Debug.WriteLine("========================================");
        }

