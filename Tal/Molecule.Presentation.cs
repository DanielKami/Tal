        /// <summary>
        /// Packing with directional + fractional bounds in crystal axes.
        /// Atom image at (x+ix,y+iy,z+iz) is kept only if min ≤ coord &lt; max on each axis.
        /// Example: minX=-1, maxX=1 → expand one cell left and keep base cell;
        /// maxX=0.5 → only the lower half of the cell along a.
        /// </summary>
        private int Calculate_SymmetryAtoms3D_Packing(
            float minX, float maxX, float minY, float maxY, float minZ, float maxZ,
            List<AtomSimple> data, int style)
        {
            if (data == null || data.Count == 0)
            {
                atom = new Atom[1];
                NumberOfAtoms = 0;
                return 0;
            }

            if (maxX < minX) (minX, maxX) = (maxX, minX);
            if (maxY < minY) (minY, maxY) = (maxY, minY);
            if (maxZ < minZ) (minZ, maxZ) = (maxZ, minZ);

            const float eps = 1e-5f;
            if (maxX - minX < eps) maxX = minX + 1f;
            if (maxY - minY < eps) maxY = minY + 1f;
            if (maxZ - minZ < eps) maxZ = minZ + 1f;

            float dataMinX = float.MaxValue, dataMaxX = float.MinValue;
            float dataMinY = float.MaxValue, dataMaxY = float.MinValue;
            float dataMinZ = float.MaxValue, dataMaxZ = float.MinValue;
            for (int n = 0; n < data.Count; n++)
            {
                var a = data[n];
                if (a.x < dataMinX) dataMinX = a.x;
                if (a.x > dataMaxX) dataMaxX = a.x;
                if (a.y < dataMinY) dataMinY = a.y;
                if (a.y > dataMaxY) dataMaxY = a.y;
                if (a.z < dataMinZ) dataMinZ = a.z;
                if (a.z > dataMaxZ) dataMaxZ = a.z;
            }

            int ix0 = (int)Math.Floor(minX - dataMaxX);
            int ix1 = (int)Math.Ceiling(maxX - dataMinX);
            int iy0 = (int)Math.Floor(minY - dataMaxY);
            int iy1 = (int)Math.Ceiling(maxY - dataMinY);
            int iz0 = (int)Math.Floor(minZ - dataMaxZ);
            int iz1 = (int)Math.Ceiling(maxZ - dataMinZ);

            int nx = Math.Max(1, ix1 - ix0 + 1);
            int ny = Math.Max(1, iy1 - iy0 + 1);
            int nz = Math.Max(1, iz1 - iz0 + 1);
            int capacity = Math.Max(data.Count * nx * ny * nz + 1, data.Count + 1);

            Matrix U = Matrix.Transpose(FractionaltoCarttesianMatrix(0, 0, 0));

            atom = new Atom[capacity];
            NumberOfAtoms = 0;

            void InitAtomSlot(int i)
            {
                atom[i].show = true;
                atom[i].Distance = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].BondOccupancy = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].AngleZ = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].AngleXY = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].BondedAtom = new int[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].H_Distance = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[i].H_AngleZ = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[i].H_AngleXY = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[i].H_BondedAtom = new int[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[i].UseForHBonds = true;
                atom[i].UseForShortContacts = true;
            }

            for (int i = 0; i < atom.Length; i++)
                InitAtomSlot(i);

            for (int iz = iz0; iz <= iz1; iz++)
            for (int iy = iy0; iy <= iy1; iy++)
            for (int ix = ix0; ix <= ix1; ix++)
            {
                for (int n = 0; n < data.Count; n++)
                {
                    float fx = data[n].x + ix;
                    float fy = data[n].y + iy;
                    float fz = data[n].z + iz;

                    if (fx < minX || fx >= maxX) continue;
                    if (fy < minY || fy >= maxY) continue;
                    if (fz < minZ || fz >= maxZ) continue;

                    if (NumberOfAtoms >= atom.Length - 1)
                    {
                        var grown = new Atom[atom.Length * 2];
                        System.Array.Copy(atom, grown, NumberOfAtoms);
                        atom = grown;
                        for (int g = NumberOfAtoms; g < atom.Length; g++)
                            InitAtomSlot(g);
                    }

                    Vector3 shift = new Vector3(fx, fy, fz);
                    atom[NumberOfAtoms].Coordinate = Vector3.Transform(shift, U);

                    atom[NumberOfAtoms].Coordinate_error.X = data[n].x_e;
                    atom[NumberOfAtoms].Coordinate_error.Y = data[n].y_e;
                    atom[NumberOfAtoms].Coordinate_error.Z = data[n].z_e;

atom[NumberOfAtoms].AtomicNumber = data[n].AtomicNumber;
                            atom[NumberOfAtoms].Ue = data[n].Ue;
                            atom[NumberOfAtoms].Un = data[n].Un;
                            atom[NumberOfAtoms].occupancy = data[n].occupancy;
                            atom[NumberOfAtoms].style = style;
                            atom[NumberOfAtoms].name = data[n].name;
                            atom[NumberOfAtoms].Transformation = data[n].Transformation;
                            atom[NumberOfAtoms].disorder_group = data[n].disorder_group;
                            atom[NumberOfAtoms].charge = data[n].charge;
                            atom[NumberOfAtoms].Hydrophobicity = data[n].Hydrophobicity;
                            atom[NumberOfAtoms].isAnisotropic = data[n].isAnisotropic;

                            atom[NumberOfAtoms].IndividualMoleculeInCell = data[n].IndividualMoleculeInCell;
                            atom[NumberOfAtoms].CustomColor = new Vector3(-1f, -1f, -1f);
                            atom[NumberOfAtoms].SymmetryEquivalentNumberInCell = data[n].SymmetryEquivalentNumberInCell;

                            atom[NumberOfAtoms].CellShiftX = ix;
                            atom[NumberOfAtoms].CellShiftY = iy;
                            atom[NumberOfAtoms].CellShiftZ = iz;

                            NumberOfAtoms++;
                }
            }

            Debug.WriteLine(
                $"[Packing] {NumberOfAtoms} atoms, box X[{minX:F2},{maxX:F2}] ix=[{ix0}..{ix1}]");
            return NumberOfAtoms;
        }

        private int Calculate_SymmetryAtoms3D(int repeatx_start, int repeatx_end, int repeaty_start, int repeaty_end,
                                              int repeatz_start, int repeatz_end, List<AtomSimple> data, int style)
        {
            Matrix U = Matrix.Transpose(FractionaltoCarttesianMatrix(0, 0, 0));

            int delta_x = repeatx_end - repeatx_start;
            int delta_y = repeaty_end - repeaty_start;
            int delta_z = repeatz_end - repeatz_start;

            atom = new Atom[data.Count * delta_x * delta_y * delta_z + 1];
            NumberOfAtoms = 0;

            for (int i = 0; i < atom.Length; i++)
            {
                atom[i].show = true;
                atom[i].Distance = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].BondOccupancy = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].AngleZ = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].AngleXY = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].BondedAtom = new int[Flags.Instance.MAX_BONDED_ATOMS];
                atom[i].H_Distance = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[i].H_AngleZ = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[i].H_AngleXY = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[i].H_BondedAtom = new int[Flags.Instance.MAX_H_BONDED_ATOMS];

                atom[i].UseForHBonds = true;
                atom[i].UseForShortContacts = true;
            }

            int totalAdded = 0;

            for (int repeatz_ = repeatz_start; repeatz_ < repeatz_end; repeatz_++)
            {
                for (int repeaty_ = repeaty_start; repeaty_ < repeaty_end; repeaty_++)
                {
                    for (int repeatx_ = repeatx_start; repeatx_ < repeatx_end; repeatx_++)
                    {
                        for (int n = 0; n < data.Count; n++)
                        {
                            Vector3 shift = new Vector3(data[n].x + repeatx_, data[n].y + repeaty_, data[n].z + repeatz_);
                            atom[NumberOfAtoms].Coordinate = Vector3.Transform(shift, U);

                            atom[NumberOfAtoms].Coordinate_error.X = data[n].x_e;
                            atom[NumberOfAtoms].Coordinate_error.Y = data[n].y_e;
                            atom[NumberOfAtoms].Coordinate_error.Z = data[n].z_e;

                            atom[NumberOfAtoms].AtomicNumber = data[n].AtomicNumber;
                            atom[NumberOfAtoms].Ue = data[n].Ue;
                            atom[NumberOfAtoms].Un = data[n].Un;
                            atom[NumberOfAtoms].occupancy = data[n].occupancy;
                            atom[NumberOfAtoms].style = style;
                            atom[NumberOfAtoms].name = data[n].name;
                            atom[NumberOfAtoms].Transformation = data[n].Transformation;
                            atom[NumberOfAtoms].disorder_group = data[n].disorder_group;
                            atom[NumberOfAtoms].charge = data[n].charge;
                            atom[NumberOfAtoms].Hydrophobicity = data[n].Hydrophobicity;
                            atom[NumberOfAtoms].isAnisotropic = data[n].isAnisotropic;

                            atom[NumberOfAtoms].IndividualMoleculeInCell = data[n].IndividualMoleculeInCell;
                            atom[NumberOfAtoms].CustomColor = new Vector3(-1f, -1f, -1f);
                            atom[NumberOfAtoms].SymmetryEquivalentNumberInCell = data[n].SymmetryEquivalentNumberInCell;

                            atom[NumberOfAtoms].CellShiftX = repeatx_;
                            atom[NumberOfAtoms].CellShiftY = repeaty_;
                            atom[NumberOfAtoms].CellShiftZ = repeatz_;

                            NumberOfAtoms++;
                            totalAdded++;
                        }
                    }
                }
            }

            Debug.WriteLine($"[Calculate_SymmetryAtoms3D] Generated {NumberOfAtoms} atoms (added {totalAdded} new)");

            return NumberOfAtoms;
        }

 /// <summary>
 /// Adds atoms from the list to atom[] with proper CellShift, array
 /// allocation, and registration in ExpandedAtomIndices.
 /// Sets UseForShortContacts = true, UseForHBonds = false.
 /// </summary>
        private int AddNearbyAtomsInternal(List<AtomSimple> newAtoms)
        {
            if (newAtoms == null || newAtoms.Count == 0) return 0;

            int style = Flags.Instance.Presentation;
            Matrix U = Matrix.Transpose(FractionaltoCarttesianMatrix(0, 0, 0));
            Vector3 shift = MoleculeShift;

            int oldCount = NumberOfAtoms;
            var newArray = new Atom[oldCount + newAtoms.Count];
            Array.Copy(atom, newArray, oldCount);
            atom = newArray;

            int added = 0;
            foreach (var na in newAtoms)
            {
                int idx = NumberOfAtoms;

                atom[idx].Distance = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[idx].BondOccupancy = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[idx].BondedAtom = new int[Flags.Instance.MAX_BONDED_ATOMS];
                atom[idx].AngleZ = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[idx].AngleXY = new float[Flags.Instance.MAX_BONDED_ATOMS];
                atom[idx].NrBondedAtoms = 0;

                atom[idx].H_Distance = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[idx].H_AngleZ = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[idx].H_AngleXY = new float[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[idx].H_BondedAtom = new int[Flags.Instance.MAX_H_BONDED_ATOMS];
                atom[idx].H_NrBondedAtoms = 0;

                Vector3 fracPos = new Vector3(na.x, na.y, na.z);
                atom[idx].Coordinate = Vector3.Transform(fracPos, U) - shift;

                atom[idx].AtomicNumber = na.AtomicNumber;
                atom[idx].name = na.name;
                atom[idx].style = style;
                atom[idx].occupancy = na.occupancy;
                atom[idx].show = true;
                atom[idx].selected = false;
                atom[idx].SelectionOrder = 0;
                atom[idx].Coordinate_error = new Vector3(na.x_e, na.y_e, na.z_e);

                atom[idx].Ue = na.Ue;
                atom[idx].Un = na.Un;
                atom[idx].Transformation = na.Transformation;

                atom[idx].disorder_group = na.disorder_group;
                atom[idx].charge = na.charge;
                atom[idx].Hydrophobicity = na.Hydrophobicity;
                atom[idx].isAnisotropic = na.isAnisotropic;
                atom[idx].SymmetryEquivalentNumberInCell = na.SymmetryEquivalentNumberInCell;
                atom[idx].IndividualMoleculeInCell = na.IndividualMoleculeInCell;

                atom[idx].CustomColor = new Vector3(-1f, -1f, -1f);

                atom[idx].CellShiftX = na.CellShiftX;
                atom[idx].CellShiftY = na.CellShiftY;
                atom[idx].CellShiftZ = na.CellShiftZ;

                atom[idx].ContactCount = 0;
                atom[idx].ContactDistance = null;
                atom[idx].ContactAtom = null;
                atom[idx].ContactAngleZ = null;
                atom[idx].ContactAngleXY = null;
                atom[idx].PrecomputedContactMatrix = null;
                atom[idx].ContactIsNew = null;

                atom[idx].PrecomputedBondMatrix = null;
                atom[idx].PrecomputedHBondMatrix = null;

                atom[idx].Z_Depth = 0;

                atom[idx].UseForHBonds = false;
                atom[idx].UseForShortContacts = true;

                NumberOfAtoms++;
                added++;
            }

            if (added > 0)
            {
                RegisterExpandedAtoms(oldCount, added);
            }

            Debug.WriteLine($"[AddNearbyAtomsInternal] Added {added} atoms " +
                            $"(total: {NumberOfAtoms}, expanded list: {ExpandedAtomIndices.Count})");

            return added;
        }

