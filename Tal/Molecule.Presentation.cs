 /// <summary>
 /// Shifts the ASYMMETRIC PART so that its geometric centre (fractional)
 /// lands at (0.5, 0.5, 0.5) — cell centre.
 /// </summary>
        private void CenterAsymmetricPart3D()
        {
            if (AsymmetricPart == null || AsymmetricPart.Count == 0)
                return;

            float cx = 0, cy = 0, cz = 0;
            for (int i = 0; i < AsymmetricPart.Count; i++)
            {
                cx += AsymmetricPart[i].x;
                cy += AsymmetricPart[i].y;
                cz += AsymmetricPart[i].z;
            }
            cx /= AsymmetricPart.Count;
            cy /= AsymmetricPart.Count;
            cz /= AsymmetricPart.Count;

            int shiftX = (int)Math.Round(0.5f - cx);
            int shiftY = (int)Math.Round(0.5f - cy);
            int shiftZ = (int)Math.Round(0.5f - cz);

            for (int i = 0; i < AsymmetricPart.Count; i++)
            {
                AtomSimple shifted = AsymmetricPart[i];
                shifted.x += shiftX;
                shifted.y += shiftY;
                shifted.z += shiftZ;
                AsymmetricPart[i] = shifted;
            }

            Debug.WriteLine($"[CenterAsymmetricPart3D] atoms={AsymmetricPart.Count}, " +
                            $"center=({cx:F4},{cy:F4},{cz:F4}), " +
                            $"shift=({shiftX},{shiftY},{shiftZ})");
        }

        #region Reflow After Space Group Transform

 /// <summary>
 /// CALLED ONLY AFTER SPACE-GROUP TRANSFORMATION (P21/c ↔ P21/n etc.).
 /// </summary>
        public void ReflowAsymmetricPartAfterTransform()
        {
            if (AsymmetricPart == null || AsymmetricPart.Count == 0)
            {
                Debug.WriteLine("[Reflow] AsymmetricPart empty — nothing to do");
                return;
            }

            Debug.WriteLine(
                $"[Reflow] START — {AsymmetricPart.Count} atoms");

 // KROK 1: Wrap do [0, 1)
            for (int i = 0; i < AsymmetricPart.Count; i++)
            {
                AtomSimple a = AsymmetricPart[i];
                a.x = Wrap01Local(a.x);
                a.y = Wrap01Local(a.y);
                a.z = Wrap01Local(a.z);
                AsymmetricPart[i] = a;
            }

 // KROK 2: Grupuj after IndividualMoleculeInCell
            bool needsDetection = true;
            for (int i = 0; i < AsymmetricPart.Count; i++)
            {
                if (AsymmetricPart[i].IndividualMoleculeInCell >= 0)
                {
                    needsDetection = false;
                    break;
                }
            }

            if (needsDetection)
            {
                Debug.WriteLine("[Reflow] IndividualMoleculeInCell not set — detecting");
                DetectMolecules(AsymmetricPart, true);
            }

            var groups = new Dictionary<int, List<int>>();
            for (int i = 0; i < AsymmetricPart.Count; i++)
            {
                int molId = AsymmetricPart[i].IndividualMoleculeInCell;
                if (molId < 0) molId = 0;

                if (!groups.ContainsKey(molId))
                    groups[molId] = new List<int>();
                groups[molId].Add(i);
            }

            Debug.WriteLine($"[Reflow] Groups: {groups.Count}");

            foreach (var kvp in groups)
            {
                var indices = kvp.Value;
                if (indices.Count == 0) continue;

                int anchorIdx = indices[0];
                int bestZ = -1;

                foreach (int idx in indices)
                {
                    int z = AsymmetricPart[idx].AtomicNumber;
                    if (z == 1) continue;
                    if (z > bestZ)
                    {
                        bestZ = z;
                        anchorIdx = idx;
                    }
                }

                if (bestZ < 0) anchorIdx = indices[0];

                float ax = AsymmetricPart[anchorIdx].x;
                float ay = AsymmetricPart[anchorIdx].y;
                float az = AsymmetricPart[anchorIdx].z;

                int reflowed = 0;
                foreach (int idx in indices)
                {
                    if (idx == anchorIdx) continue;

                    AtomSimple a = AsymmetricPart[idx];

                    float dx = a.x - ax;
                    float dy = a.y - ay;
                    float dz = a.z - az;

                    float rdx = dx - (float)Math.Round(dx);
                    float rdy = dy - (float)Math.Round(dy);
                    float rdz = dz - (float)Math.Round(dz);

                    if (Math.Abs(rdx - dx) > 1e-6f ||
                        Math.Abs(rdy - dy) > 1e-6f ||
                        Math.Abs(rdz - dz) > 1e-6f)
                    {
                        reflowed++;
                    }

                    a.x = ax + rdx;
                    a.y = ay + rdy;
                    a.z = az + rdz;
                    AsymmetricPart[idx] = a;
                }

                int shiftX = (int)Math.Round(0.5f - ax);
                int shiftY = (int)Math.Round(0.5f - ay);
                int shiftZ = (int)Math.Round(0.5f - az);

                if (shiftX != 0 || shiftY != 0 || shiftZ != 0)
                {
                    foreach (int idx in indices)
                    {
                        AtomSimple a = AsymmetricPart[idx];
                        a.x += shiftX;
                        a.y += shiftY;
                        a.z += shiftZ;
                        AsymmetricPart[idx] = a;
                    }
                }

                Debug.WriteLine(
                    $"[Reflow] Mol {kvp.Key}: {indices.Count} atoms, " +
                    $"anchor={AsymmetricPart[anchorIdx].name} " +
                    $"({ax:F3},{ay:F3},{az:F3}), " +
                    $"reflowed={reflowed}, shift=({shiftX},{shiftY},{shiftZ})");
            }

            Debug.WriteLine("[Reflow] END");
        }

        private static float Wrap01Local(float v)
        {
            float r = v - (float)Math.Floor(v);
            if (r >= 1f) r -= 1f;
            if (r < 0f) r += 1f;
            return r;
        }

        #endregion

 /// <summary>
 /// Centers each detected molecule at fractional (0.5, 0.5, 0.5)
 /// by shifting whole molecules (integer cell translations).
 /// </summary>
        private void CenterMolecules3D()
        {
            if (SymetryEquivalents.Count == 0)
                return;

            var moleculeGroups = new Dictionary<int, List<AtomSimple>>();
            for (int i = 0; i < SymetryEquivalents.Count; i++)
            {
                int molNum = SymetryEquivalents[i].SymmetryEquivalentNumberInCell;
                if (!moleculeGroups.ContainsKey(molNum))
                    moleculeGroups[molNum] = new List<AtomSimple>();
                moleculeGroups[molNum].Add(SymetryEquivalents[i]);
            }

            var centeredAtoms = new List<AtomSimple>();

            foreach (var group in moleculeGroups)
            {
                int molNum = group.Key;
                var atoms = group.Value;

                float cx = 0, cy = 0, cz = 0;
                foreach (var atom in atoms)
                {
                    cx += atom.x;
                    cy += atom.y;
                    cz += atom.z;
                }
                cx /= atoms.Count;
                cy /= atoms.Count;
                cz /= atoms.Count;

                float targetX = 0.5f;
                float targetY = 0.5f;
                float targetZ = 0.5f;

                int shiftX = (int)Math.Round(targetX - cx);
                int shiftY = (int)Math.Round(targetY - cy);
                int shiftZ = (int)Math.Round(targetZ - cz);

                foreach (var atom in atoms)
                {
                    AtomSimple shifted = atom;
                    shifted.x += shiftX;
                    shifted.y += shiftY;
                    shifted.z += shiftZ;
                    centeredAtoms.Add(shifted);
                }
            }

            SymetryEquivalents.Clear();
            SymetryEquivalents.AddRange(centeredAtoms);
        }

 /// <summary>
 /// Centers the 3D atom cloud at origin (Cartesian).
 /// Respektuje Flags.AutoCentre.
 /// </summary>
        private void CenterAtoms3D()
        {
            if (NumberOfAtoms == 0)
            {
                MoleculeShift = Vector3.Zero;
                MoleculeShiftChanged?.Invoke(MoleculeShift);
                return;
            }

            bool autoCentre = Flags.Instance.AutoCentre;

            if (autoCentre)
            {
                FindCenter();
                for (int i = 0; i < NumberOfAtoms; i++)
                {
                    atom[i].Coordinate.X -= MoleculeShift.X;
                    atom[i].Coordinate.Y -= MoleculeShift.Y;
                    atom[i].Coordinate.Z -= MoleculeShift.Z;
                }
            }
            else
            {
                MoleculeShift = Vector3.One / 2;

                for (int i = 0; i < NumberOfAtoms; i++)
                {
                    atom[i].Coordinate.X -= MoleculeShift.X;
                    atom[i].Coordinate.Y -= MoleculeShift.Y;
                    atom[i].Coordinate.Z -= MoleculeShift.Z;
                }
            }

            MoleculeShiftChanged?.Invoke(MoleculeShift);
            Debug.WriteLine("[Molecule] MoleculeShift {" + MoleculeShift.X + ", " + MoleculeShift.Y + ", " + MoleculeShift.Z + "}");
        }

        void FindCenter()
        {
            float tempX = 0, tempY = 0, tempZ = 0;

            for (int i = 0; i < NumberOfAtoms; i++)
            {
                tempX += atom[i].Coordinate.X;
                tempY += atom[i].Coordinate.Y;
                tempZ += atom[i].Coordinate.Z;
            }

            MoleculeShift.X = tempX / NumberOfAtoms;
            MoleculeShift.Y = tempY / NumberOfAtoms;
            MoleculeShift.Z = tempZ / NumberOfAtoms;
        }

        Vector3 FindCenterAsymetricPArt()
        {
            Vector3 local_shift = Vector3.Zero;
            float tempX = 0, tempY = 0, tempZ = 0;

            for (int i = 0; i < AsymmetricPart.Count; i++)
            {
                tempX += atom[i].Coordinate.X;
                tempY += atom[i].Coordinate.Y;
                tempZ += atom[i].Coordinate.Z;
            }

            local_shift.X = tempX / NumberOfAtoms;
            local_shift.Y = tempY / NumberOfAtoms;
            local_shift.Z = tempZ / NumberOfAtoms;
            return local_shift;
        }

